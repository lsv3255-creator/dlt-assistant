"""Shuangseqiu comprehensive analysis sections (DLT homepage parity).

DLT's analysis text is produced by its own LLM steps (the API key is
only injected into those workflow steps). For the newer lotteries the
same section structure is generated by a deterministic statistics
engine: every sentence is interpolated from computed facts (frequency,
omission, sums, spans, structures), so the analysis is fully
traceable to the stored draw history. Sections mirror ai_cycle:
trend / hot_cold / structure / basis / risk.
"""
from __future__ import annotations

from . import stats


def _fmt(nums) -> str:
    return "、".join(f"{n:02d}" for n in nums)


def build_analysis(rows: list[dict], picks: list[dict], target: dict) -> dict:
    summary = stats.summarize(rows)
    freq_100 = summary["frequency_100"]
    omit = summary["omission"]
    recent = rows[-10:]
    sums = [sum(r["red"]) for r in recent]
    spans = [max(r["red"]) - min(r["red"]) for r in recent]
    last, prev = rows[-1], rows[-2]
    repeats = sorted(set(last["red"]) & set(prev["red"]))
    consecutive = any(
        b - a == 1 for a, b in zip(last["red"], last["red"][1:])
    )

    trend = (
        f"近10期红球和值均值 {sum(sums) / len(sums):.1f}，跨度均值 "
        f"{sum(spans) / len(spans):.1f}。最新一期（第{last['issue']}期）和值 "
        f"{sum(last['red'])}、跨度 {max(last['red']) - min(last['red'])}，"
        f"与上期重号 {len(repeats)} 个"
        + (f"（{_fmt(repeats)}）" if repeats else "")
        + ("，含连号。" if consecutive else "，无连号。")
    )

    hot_red = summary["hot"]["red"]
    cold_red = summary["cold"]["red"]
    hot_cold = (
        f"近100期热号红球 {_fmt(hot_red)}（最高频 "
        f"{freq_100['red'][hot_red[0]]} 次）；遗漏最久的红球 "
        + "、".join(f"{n:02d}（{omit['red'][n]}期）" for n in cold_red[:3])
        + f"。蓝球近100期最热 {summary['hot']['blue'][0]:02d}"
        f"（{freq_100['blue'][summary['hot']['blue'][0]]} 次），最冷 "
        f"{summary['cold']['blue'][0]:02d}"
        f"（遗漏 {omit['blue'][summary['cold']['blue'][0]]} 期）。"
    )

    sample100 = rows[-100:]
    zone_counts = [0, 0, 0]
    odd = 0
    big = 0
    total_balls = 0
    for r in sample100:
        for n in r["red"]:
            zone_counts[0 if n <= 11 else (1 if n <= 22 else 2)] += 1
            odd += n % 2
            big += 1 if n >= 17 else 0
            total_balls += 1
    sum_hist: dict[int, int] = {}
    for r in sample100:
        bucket = sum(r["red"]) // 10 * 10
        sum_hist[bucket] = sum_hist.get(bucket, 0) + 1
    top_bucket = max(sum_hist, key=lambda b: sum_hist[b])
    structure = (
        f"近100期红球三区（一区01-11/二区12-22/三区23-33）占比 "
        f"{zone_counts[0] / total_balls:.0%}/{zone_counts[1] / total_balls:.0%}/"
        f"{zone_counts[2] / total_balls:.0%}，奇偶比约 "
        f"{odd / total_balls:.0%}:{(total_balls - odd) / total_balls:.0%}，"
        f"大小比（≥17为大）约 {big / total_balls:.0%}:"
        f"{(total_balls - big) / total_balls:.0%}。和值最集中区间为 "
        f"{top_bucket}-{top_bucket + 9}（{sum_hist[top_bucket]} 期）。"
    )

    pick_a, pick_b = picks[0], picks[1]
    basis = (
        f"A-均衡统计型选 {_fmt(pick_a['red'])} + {pick_a['blue']:02d}："
        "按近100期频率叠加遗漏加分的均衡评分、三区各取2个最高分；"
        f"B-冷热组合型选 {_fmt(pick_b['red'])} + {pick_b['blue']:02d}："
        "3 个热号 + 2 个高遗漏冷号 + 1 个均衡分最高号；"
        "C 为按目标期号做种子的纯随机娱乐组合。"
    )

    risk = (
        "以上分析全部来自历史开奖的统计事实。彩票每期独立随机，"
        "冷热、遗漏与和值分布都不改变单注中奖概率（双色球一等奖约 "
        "1/17,721,088）。推荐为娱乐参考，请量力而行。"
    )

    return {
        "target_issue": target["issue"],
        "target_date": target["date"],
        "source": "stats-engine",
        "sections": {
            "trend": trend,
            "hot_cold": hot_cold,
            "structure": structure,
            "basis": basis,
            "risk": risk,
        },
    }
