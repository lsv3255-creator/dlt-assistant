"""Fucai 3D comprehensive analysis sections (DLT homepage parity).

Generated by a deterministic statistics engine from the stored draw
history (the DLT LLM key is only injected into DLT's own workflow
steps). Sections mirror ai_cycle: trend / hot_cold / structure /
basis / risk. Every number in the text is computed from real draws.
"""
from __future__ import annotations

from . import stats

POS_NAMES = ["百位", "十位", "个位"]


def draw_form(digits: list[int]) -> str:
    unique = len(set(digits))
    return "豹子" if unique == 1 else ("组三" if unique == 2 else "组六")


def build_analysis(rows: list[dict], picks: list[dict], target: dict) -> dict:
    summary = stats.summarize(rows)
    freq_100 = summary["frequency_100"]
    omit = summary["omission"]
    recent = rows[-10:]
    sums = [sum(r["digits"]) for r in recent]
    spans = [max(r["digits"]) - min(r["digits"]) for r in recent]
    last, prev = rows[-1], rows[-2]
    pos_repeats = sum(
        1 for a, b in zip(last["digits"], prev["digits"]) if a == b
    )
    trend = (
        f"近10期和值均值 {sum(sums) / len(sums):.1f}，跨度均值 "
        f"{sum(spans) / len(spans):.1f}。最新一期（第{last['issue']}期）开 "
        f"{''.join(map(str, last['digits']))}，和值 {sum(last['digits'])}、"
        f"跨度 {max(last['digits']) - min(last['digits'])}、形态 "
        f"{draw_form(last['digits'])}，与上期同位重号 {pos_repeats} 个。"
    )

    hot_cold = "；".join(
        f"{POS_NAMES[pos]}热号 {summary['hot'][pos]}"
        f"（近100期 {freq_100['per_position'][pos][summary['hot'][pos]]} 次）、"
        f"冷号 {summary['cold'][pos]}"
        f"（遗漏 {omit[pos][summary['cold'][pos]]} 期）"
        for pos in range(3)
    ) + "。"

    sample100 = rows[-100:]
    form_counts = {"豹子": 0, "组三": 0, "组六": 0}
    odd = 0
    for r in sample100:
        form_counts[draw_form(r["digits"])] += 1
        odd += sum(d % 2 for d in r["digits"])
    total_digits = 300
    structure = (
        f"近100期形态分布：组六 {form_counts['组六']} 期、组三 "
        f"{form_counts['组三']} 期、豹子 {form_counts['豹子']} 期；"
        f"奇偶比约 {odd / total_digits:.0%}:{(total_digits - odd) / total_digits:.0%}；"
        f"最常见和值 {summary['common_sum_100']}。"
    )

    pick_a, pick_b = picks[0], picks[1]
    basis = (
        f"A-均衡统计型选 {''.join(map(str, pick_a['digits']))}：各位按"
        "近100期频率叠加遗漏加分取最高分；"
        f"B-冷热组合型选 {''.join(map(str, pick_b['digits']))}：百位取热号、"
        "十位取遗漏最久的冷号、个位取均衡分最高；C 为按目标期号做种子的"
        "纯随机娱乐组合。"
    )

    risk = (
        "以上分析全部来自历史开奖的统计事实。福彩3D 每位独立随机，"
        "冷热与遗漏不改变单注概率（直选 1/1000）。推荐为娱乐参考，"
        "请量力而行。"
    )

    return {
        "target_issue": target["issue"],
        "target_date": target["date"],
        "source": "stats-engine",
        "sections": {
            "trend": trend,
            "hot_cold": hot_cold,
            "structure": structure,
            "basis": basis,
            "risk": risk,
        },
    }
