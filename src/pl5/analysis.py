"""Pailie 5 comprehensive analysis sections (DLT homepage parity).

Generated by a deterministic statistics engine from the stored draw
history. Sections mirror ai_cycle: trend / hot_cold / structure /
basis / risk. Every number in the text is computed from real draws.
"""
from __future__ import annotations

from . import stats

POS_NAMES = ["万位", "千位", "百位", "十位", "个位"]


def build_analysis(rows: list[dict], picks: list[dict], target: dict) -> dict:
    summary = stats.summarize(rows)
    freq_100 = summary["frequency_100"]
    omit = summary["omission"]
    recent = rows[-10:]
    sums = [sum(r["digits"]) for r in recent]
    spans = [max(r["digits"]) - min(r["digits"]) for r in recent]
    last, prev = rows[-1], rows[-2]
    pos_repeats = sum(
        1 for a, b in zip(last["digits"], prev["digits"]) if a == b
    )
    trend = (
        f"近10期和值均值 {sum(sums) / len(sums):.1f}，跨度均值 "
        f"{sum(spans) / len(spans):.1f}。最新一期（第{last['issue']}期）开 "
        f"{''.join(map(str, last['digits']))}，和值 {sum(last['digits'])}、"
        f"跨度 {max(last['digits']) - min(last['digits'])}，"
        f"与上期同位重号 {pos_repeats} 个。"
    )

    hot_cold = "；".join(
        f"{POS_NAMES[pos]}热号 {summary['hot'][pos]}"
        f"（近100期 {freq_100['per_position'][pos][summary['hot'][pos]]} 次）、"
        f"冷号 {summary['cold'][pos]}"
        f"（遗漏 {omit[pos][summary['cold'][pos]]} 期）"
        for pos in range(5)
    ) + "。"

    sample100 = rows[-100:]
    odd = sum(sum(d % 2 for d in r["digits"]) for r in sample100)
    total_digits = 500
    structure = (
        f"近100期最常见和值 {summary['common_sum_100']}；奇偶占比约 "
        f"{odd / total_digits:.0%}:{(total_digits - odd) / total_digits:.0%}；"
        f"五位平均跨度 {sum(max(r['digits']) - min(r['digits']) for r in sample100) / 100:.1f}。"
    )

    pick_a, pick_b = picks[0], picks[1]
    basis = (
        f"A-均衡统计型选 {''.join(map(str, pick_a['digits']))}：各位按"
        "近100期频率叠加遗漏加分取最高分；"
        f"B-冷热组合型选 {''.join(map(str, pick_b['digits']))}：万/个位取热号、"
        "千/十位取冷号、百位取均衡分最高；C 为按目标期号做种子的纯随机"
        "娱乐组合。"
    )

    risk = (
        "以上分析全部来自历史开奖的统计事实。排列五每位独立随机，"
        "冷热与遗漏不改变单注概率（一等奖 1/100000）。推荐为娱乐参考，"
        "请量力而行。"
    )

    return {
        "target_issue": target["issue"],
        "target_date": target["date"],
        "source": "stats-engine",
        "sections": {
            "trend": trend,
            "hot_cold": hot_cold,
            "structure": structure,
            "basis": basis,
            "risk": risk,
        },
    }
